def main() -> None:
    files = sorted(p for p in TRAD.glob("*.md") if p.name != "comparative-overview.md")
    records = []
    for path in files:
        meta = parse_md(path)
        slug = meta["slug"]
        r = resolve(slug, meta["overview"])
        h = abs(hash(slug)) % 1000
        jlat = ((h % 20) - 10) * 0.025
        jlon = (((h // 20) % 20) - 10) * 0.025
        records.append({
            "id": slug,
            "slug": slug,
            "title": meta["title"],
            "grade": meta["grade"],
            "region": r["region"],
            "lat": round(r["lat"] + jlat, 4),
            "lon": round(r["lon"] + jlon, 4),
            "year_start": r["year_start"],
            "year_end": r["year_end"],
            "date_basis": r["date_basis"],
            "date_note": r["date_note"],
            "confidence": r["confidence"],
            "github_url": GITHUB.format(slug=slug),
        })
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(records, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"Wrote {len(records)} -> {OUT}")
    print("date_basis:", dict(Counter(x["date_basis"] for x in records)))
    print("confidence:", dict(Counter(x["confidence"] for x in records)))
    print("grade:", dict(Counter(x["grade"] for x in records)))
    ys = [x["year_start"] for x in records]
    print("year range:", min(ys), max(ys))
    low = [x["slug"] for x in records if x["confidence"] == "low"]
    print("low_confidence count:", len(low))
    unk = [x["slug"] for x in records if x["region"] == "未定／全球"]
    print("unlocated:", len(unk), unk[:30])


if __name__ == "__main__":
    main()
