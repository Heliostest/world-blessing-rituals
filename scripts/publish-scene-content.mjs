import { readFile, writeFile, mkdir, copyFile, rename } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { parsePack } from "../packages/content/src/index.ts";
import { validateWoodfishGLB } from "../packages/content/src/glb.ts";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
export const contentOutput = path.join(root, "artifacts/scene-content");
const ref = async (file) => {
  const bytes = await readFile(path.join(root, file));
  return {
    path: file.replace(/^assets\//, ""),
    bytes: bytes.length,
    sha256: createHash("sha256").update(bytes).digest("hex"),
  };
};
async function validateModel(file, bindings) {
  const bytes = await readFile(path.join(root, file));
  validateWoodfishGLB(
    bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
    bindings,
  );
}
export async function prepareBundledContent() {
  // Independently authored against the shipped GLB, never the remote descriptor.
  const source = JSON.parse(
    await readFile(path.join(root, "content/woodfish/bundled.json"), "utf8"),
  );
  const bundled = parsePack({
    ...source,
    model: await ref("assets/woodfish/bundled-v1/woodfish.glb"),
  });
  await validateModel(
    "assets/woodfish/bundled-v1/woodfish.glb",
    bundled.bindings,
  );
  const file = path.join(root, "packages/content/src/bundled.ts");
  const text = `// Generated by prepare-app-assets.mjs from content/woodfish/bundled.json.\nimport { parsePack } from "./index";\nexport const bundledWoodfish = parsePack(${JSON.stringify(bundled, null, 2)});\n`;
  if ((await readFile(file, "utf8").catch(() => "")) !== text)
    await writeFile(file, text);
}
export async function publishSceneContent() {
  const source = JSON.parse(
    await readFile(path.join(root, "content/woodfish/pack.json"), "utf8"),
  );
  const model = await ref("assets/woodfish/blender-v2/woodfish.glb");
  await mkdir(contentOutput, { recursive: true });
  const name = `${model.sha256}.glb`;
  await copyFile(
    path.join(root, "assets", model.path),
    path.join(contentOutput, name),
  );
  const pack = { ...source, model: { ...model, path: name } };
  if (process.env.WBR_SCENE_SOUND) {
    const file = path.resolve(root, process.env.WBR_SCENE_SOUND);
    const bytes = await readFile(file),
      ext = path.extname(file).toLowerCase();
    if (
      ![".wav", ".mp3", ".ogg"].includes(ext) ||
      bytes.length > 4 * 1024 * 1024
    )
      throw Error("Unsupported scene sound");
    const sha256 = createHash("sha256").update(bytes).digest("hex");
    pack.sound = { path: `${sha256}${ext}`, sha256, bytes: bytes.length };
    await copyFile(file, path.join(contentOutput, pack.sound.path));
  }
  parsePack(pack);
  await validateModel("assets/woodfish/blender-v2/woodfish.glb", pack.bindings);
  const fingerprint = createHash("sha256")
    .update(JSON.stringify(parsePack(pack)))
    .digest("hex")
    .slice(0, 12);
  pack.revision = `${pack.revision}-${fingerprint}`;
  parsePack(pack);
  const releaseText = JSON.stringify(pack, null, 2);
  await mkdir(path.join(contentOutput, "releases"), { recursive: true });
  const releasePath = path.join(
    contentOutput,
    "releases",
    `${pack.revision}.json`,
  );
  try {
    await writeFile(releasePath, releaseText, { flag: "wx" });
  } catch (error) {
    if (
      error.code !== "EEXIST" ||
      (await readFile(releasePath, "utf8")) !== releaseText
    )
      throw error;
  }
  // Upload immutable assets first; replace the small channel manifest last.
  await writeFile(path.join(contentOutput, "woodfish.json.tmp"), releaseText);
  await rename(
    path.join(contentOutput, "woodfish.json.tmp"),
    path.join(contentOutput, "woodfish.json"),
  );
  return pack;
}
if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const pack = await publishSceneContent();
  console.log(`Published ${pack.revision} to ${contentOutput}`);
}
